-- Initialize database schema for RAG Infrastructure

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- Sources table
CREATE TABLE IF NOT EXISTS sources (
    source_id TEXT PRIMARY KEY,
    source_type TEXT NOT NULL,
    file_name TEXT NOT NULL,
    file_path TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Chunks table with Full-Text Search tsvector
CREATE TABLE IF NOT EXISTS chunks (
    chunk_id TEXT PRIMARY KEY,
    source_id TEXT REFERENCES sources(source_id) ON DELETE CASCADE,
    text TEXT NOT NULL,
    chunk_index INTEGER,
    metadata JSONB DEFAULT '{}'::jsonb,
    language TEXT,
    text_search tsvector GENERATED ALWAYS AS (to_tsvector('simple', coalesce(text, ''))) STORED
);

-- Indexes for chunk retrieval
CREATE INDEX IF NOT EXISTS idx_chunks_text_search ON chunks USING GIN(text_search);
CREATE INDEX IF NOT EXISTS idx_chunks_source_id ON chunks(source_id);
CREATE INDEX IF NOT EXISTS idx_chunks_language ON chunks(language);

-- Evaluation dataset table
CREATE TABLE IF NOT EXISTS eval_dataset (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    chunk_id TEXT REFERENCES chunks(chunk_id) ON DELETE SET NULL,
    corpus_id TEXT REFERENCES sources(source_id) ON DELETE SET NULL,
    question TEXT NOT NULL,
    answer TEXT NOT NULL,
    language TEXT,
    cross_lingual BOOLEAN DEFAULT FALSE,
    chunk_text TEXT,
    source TEXT NOT NULL,
    job_id TEXT,
    reviewed BOOLEAN DEFAULT FALSE,
    review_note TEXT,
    generated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Evaluation chunk status tracking
CREATE TABLE IF NOT EXISTS eval_chunk_status (
    job_id TEXT NOT NULL,
    chunk_id TEXT NOT NULL,
    status TEXT CHECK (status IN ('generated', 'skipped', 'pending', 'failed', 'persisted')),
    reason TEXT,
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    PRIMARY KEY (job_id, chunk_id)
);

-- Write-Ahead Log table for evaluation generation
CREATE TABLE IF NOT EXISTS eval_dataset_wal (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id UUID NOT NULL,
    chunks_ids TEXT[] NOT NULL,
    raw_response TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);
