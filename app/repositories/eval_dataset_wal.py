"""
eval_dataset_wal (
id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
job_id uuid not null,
chunks_ids uuid[] not null,
raw_response text not null,
created_at TIMESTAMPTZ DEFAULT now()
);
"""
import psycopg

from app.clients import get_conn

def write_to_wal(job_id, chunk_ids: list, raw_response):
    try:
        with get_conn() as conn:
            with conn.transaction() as trans:
                with conn.cursor() as cur:
                    cur.execute(
                        """
                        INSERT INTO eval_dataset_wal (job_id, chunks_ids, raw_response)
                        VALUES (%s, %s, %s)
                        """,
                        (job_id, chunk_ids, raw_response)
                    )
    except Exception as e:
        print(f"Error writing to WAL: {e}")
        raise e
    return True

def read_from_wal(job_id):
    try:
        with get_conn() as conn:
            with conn.cursor(row_factory=psycopg.rows.dict_row) as cur:
                cur.execute(
                    """
                    SELECT * FROM eval_dataset_wal WHERE job_id = %s
                    """,
                    (job_id,)
                )
                rows = cur.fetchall()
                return rows
    except Exception as e:
        print(f"Error reading from WAL: {e}")
        raise e
    
def clean_wal(job_id, chunk_id):
    try:
        with get_conn() as conn:
            with conn.transaction() as trans:
                with conn.cursor() as cur:
                    cur.execute(
                        """
                        DELETE FROM eval_dataset_wal
                        WHERE job_id = %s AND %s = ANY(chunks_ids)
                        """,
                        (job_id, chunk_id)
                    )
    except Exception as e:
        print(f"Error cleaning WAL: {e}")
        raise e
    return True

